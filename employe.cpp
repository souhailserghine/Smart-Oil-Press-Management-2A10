// ──────────────────────────────────────────────────────────────────────────────
// CRUD – Ajouter (INSERT)
// id_emp is auto-generated by the Oracle trigger trg_emp via seq_emp.NEXTVAL
// ──────────────────────────────────────────────────────────────────────────────

bool Employe::ajouter()
{
    QSqlQuery query;
    query.prepare(
        "INSERT INTO EMPLOYE "
        "  (nom_emp, prenom_emp, email, role, mdp, photo, modele_faciale) "
        "VALUES "
        "  (:nom_emp, :prenom_emp, :email, :role, :mdp, :photo, :modele_faciale)"
    );
    query.bindValue(":nom_emp",    m_nomEmp);
    query.bindValue(":prenom_emp", m_prenomEmp);
    query.bindValue(":email",      m_email);
    query.bindValue(":role",       m_role);
    query.bindValue(":mdp",        m_mdp);

    if (m_photo.isEmpty())
        query.bindValue(":photo", QVariant(QMetaType(QMetaType::QByteArray)));
    else
        query.bindValue(":photo", m_photo);

    if (m_modeleFaciale.isEmpty())
        query.bindValue(":modele_faciale", QVariant(QMetaType(QMetaType::QByteArray)));
    else
        query.bindValue(":modele_faciale", m_modeleFaciale);

    if (!query.exec()) {
        m_lastError = query.lastError();
        qDebug() << "ajouter() error:" << m_lastError.text()
                 << "| Driver:" << m_lastError.driverText()
                 << "| DB:"     << m_lastError.databaseText();
        return false;
    }
    // Retrieve the auto-generated id_emp assigned by the trigger
    QSqlQuery idQuery;
    if (idQuery.exec("SELECT seq_emp.CURRVAL FROM DUAL") && idQuery.next()) {
        m_idEmp = idQuery.value(0).toInt();
    }
    return true;
}

// ──────────────────────────────────────────────────────────────────────────────
// CRUD – Supprimer (DELETE)
// ──────────────────────────────────────────────────────────────────────────────

bool Employe::supprimer(int id_emp)
{
    QSqlQuery query;
    query.prepare("DELETE FROM EMPLOYE WHERE id_emp = :id_emp");
    query.bindValue(":id_emp", id_emp);
    if (!query.exec()) {
        m_lastError = query.lastError();
        return false;
    }
    return true;
}

// ──────────────────────────────────────────────────────────────────────────────
// CRUD – Modifier (UPDATE)
// ──────────────────────────────────────────────────────────────────────────────

bool Employe::modifier()
{
    QSqlQuery query;

    // If mdp is empty the user left it blank → keep the existing password in DB
    if (m_mdp.isEmpty()) {
        query.prepare(
            "UPDATE EMPLOYE SET "
            "  nom_emp         = :nom_emp, "
            "  prenom_emp      = :prenom_emp, "
            "  email           = :email, "
            "  role            = :role, "
            "  photo           = :photo, "
            "  modele_faciale  = :modele_faciale "
            "WHERE id_emp = :id_emp"
        );
    } else {
        query.prepare(
            "UPDATE EMPLOYE SET "
            "  nom_emp         = :nom_emp, "
            "  prenom_emp      = :prenom_emp, "
            "  email           = :email, "
            "  role            = :role, "
            "  mdp             = :mdp, "
            "  photo           = :photo, "
            "  modele_faciale  = :modele_faciale "
            "WHERE id_emp = :id_emp"
        );
        query.bindValue(":mdp", m_mdp);
    }

    query.bindValue(":nom_emp",    m_nomEmp);
    query.bindValue(":prenom_emp", m_prenomEmp);
    query.bindValue(":email",      m_email);
    query.bindValue(":role",       m_role);

    if (m_photo.isEmpty())
        query.bindValue(":photo", QVariant(QMetaType(QMetaType::QByteArray)));
    else
        query.bindValue(":photo", m_photo);

    if (m_modeleFaciale.isEmpty())
        query.bindValue(":modele_faciale", QVariant(QMetaType(QMetaType::QByteArray)));
    else
        query.bindValue(":modele_faciale", m_modeleFaciale);

    query.bindValue(":id_emp", m_idEmp);

    if (!query.exec()) {
        m_lastError = query.lastError();
        qDebug() << "modifier() error:" << m_lastError.text()
                 << "| Driver:" << m_lastError.driverText()
                 << "| DB:"     << m_lastError.databaseText();
        return false;
    }
    return true;
}

